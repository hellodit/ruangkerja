import { createHash, createHmac } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import fixtures from '../fixtures/singapay-normalize.json'
import { computeSignature, detectEventType, normalizeBody, sha256Hex, verifySingapaySignature } from '../../server/utils/singapay'

const SECRET = 'test-hmac-key'
const PATH = '/api/webhooks/singapay'
const TOKEN = 'random-token-from-singapay'
const NOW = 1_780_000_000

function sign(body: string, opts: { secret?: string, timestamp?: number, normalized?: boolean } = {}) {
  const ts = opts.timestamp ?? NOW
  const hashed = createHash('sha256').update(opts.normalized === false ? body : normalizeBody(body)).digest('hex')
  const sts = `POST:${PATH}:${TOKEN}:${hashed}:${ts}`
  return {
    'x-signature': createHmac('sha512', opts.secret ?? SECRET).update(sts).digest('hex'),
    'x-timestamp': String(ts),
    'authorization': `Bearer ${TOKEN}`
  }
}

describe('normalizeBody (PHP json_encode(ksort) parity)', () => {
  // Expectations generated by real PHP: tests/fixtures/singapay-normalize.php
  for (const { raw, normalized } of fixtures) {
    it(`matches PHP for ${raw.slice(0, 60)}`, () => {
      expect(normalizeBody(raw)).toBe(normalized)
    })
  }

  it('throws on invalid json', () => {
    expect(() => normalizeBody('{nope')).toThrow()
    expect(() => normalizeBody('{"a":1} trailing')).toThrow()
  })
})

describe('computeSignature', () => {
  it('matches the documented string-to-sign', () => {
    const bodyHash = sha256Hex('{}')
    const expected = createHmac('sha512', SECRET).update(`POST:${PATH}:${TOKEN}:${bodyHash}:${NOW}`).digest('hex')
    expect(computeSignature({ method: 'POST', path: PATH, token: TOKEN, bodyHash, timestamp: String(NOW), secret: SECRET })).toBe(expected)
  })
})

describe('verifySingapaySignature', () => {
  const body = '{"event":"va-transaction","data":{"amount":10000,"reff_no":"INV-1"}}'
  const verify = (headers: Record<string, string | undefined>, extra: Partial<Parameters<typeof verifySingapaySignature>[0]> = {}) =>
    verifySingapaySignature({ rawBody: body, headers, path: PATH, secrets: [SECRET], now: NOW, ...extra })

  it('accepts a valid delivery signed over the normalized body', () => {
    expect(verify(sign(body))).toEqual({ ok: true })
  })

  it('accepts a delivery signed over the raw body (fallback)', () => {
    const unsorted = '{"event":"va-transaction","data":{"reff_no":"INV-1","amount":10000}}'
    const headers = sign(unsorted, { normalized: false })
    expect(verify(headers, { rawBody: unsorted })).toEqual({ ok: true })
  })

  it('accepts a signature computed over sorted keys when the raw body is unsorted', () => {
    const unsorted = '{"data":{"reff_no":"INV-1","amount":10000},"event":"va-transaction"}'
    expect(verify(sign(unsorted), { rawBody: unsorted })).toEqual({ ok: true })
  })

  it('accepts uppercase hex signatures', () => {
    const headers = sign(body)
    headers['x-signature'] = headers['x-signature'].toUpperCase()
    expect(verify(headers)).toEqual({ ok: true })
  })

  it('accepts any secret in the rotation list', () => {
    expect(verify(sign(body, { secret: 'new-key' }), { secrets: [SECRET, 'new-key'] })).toEqual({ ok: true })
  })

  it('rejects a wrong secret', () => {
    expect(verify(sign(body, { secret: 'other' }))).toEqual({ ok: false, reason: 'invalid_signature' })
  })

  it('rejects a tampered body', () => {
    expect(verify(sign(body), { rawBody: body.replace('10000', '99999') })).toEqual({ ok: false, reason: 'invalid_signature' })
  })

  it('rejects a different token', () => {
    const headers = sign(body)
    headers.authorization = 'Bearer someone-else'
    expect(verify(headers)).toEqual({ ok: false, reason: 'invalid_signature' })
  })

  it('rejects stale and future timestamps beyond tolerance', () => {
    expect(verify(sign(body, { timestamp: NOW - 301 }))).toEqual({ ok: false, reason: 'stale_timestamp' })
    expect(verify(sign(body, { timestamp: NOW + 301 }))).toEqual({ ok: false, reason: 'stale_timestamp' })
    expect(verify(sign(body, { timestamp: NOW - 300 }))).toEqual({ ok: true })
  })

  it('rejects missing or malformed headers', () => {
    const h = sign(body)
    expect(verify({ ...h, 'x-signature': undefined })).toEqual({ ok: false, reason: 'missing_headers' })
    expect(verify({ ...h, 'x-timestamp': '12a' })).toEqual({ ok: false, reason: 'missing_headers' })
    expect(verify({ ...h, authorization: undefined })).toEqual({ ok: false, reason: 'missing_headers' })
  })

  it('rejects when no secret is configured', () => {
    expect(verify(sign(body), { secrets: [] })).toEqual({ ok: false, reason: 'not_configured' })
  })

  it('rejects invalid json', () => {
    expect(verify(sign(body), { rawBody: 'not json' })).toEqual({ ok: false, reason: 'invalid_body' })
  })
})

describe('detectEventType', () => {
  it('uses the event field', () => {
    expect(detectEventType({ event: 'va-transaction' })).toBe('va-transaction')
    expect(detectEventType({ event: 'disbursement' })).toBe('disbursement')
  })

  it('normalizes underscores', () => {
    expect(detectEventType({ event: 'transaction_expiration' })).toBe('transaction-expiration')
  })

  it('maps prefixed events', () => {
    expect(detectEventType({ event: 'subscription.cycle.success' })).toBe('subscription-cycle')
    expect(detectEventType({ event: 'settlement.done' })).toBe('settlement')
    expect(detectEventType({ event: 'direct_debit.binding' })).toBe('direct-debit')
  })

  it('falls back to payment link shape', () => {
    expect(detectEventType({ data: { transaction: { type: 'pl' } } })).toBe('payment-link-transaction')
    expect(detectEventType({ data: { payment: { method: 'payment_link' } } })).toBe('payment-link-transaction')
  })

  it('returns null for unknown payloads', () => {
    expect(detectEventType({ event: 'something-new' })).toBeNull()
    expect(detectEventType({})).toBeNull()
  })
})
